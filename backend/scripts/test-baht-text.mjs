let pass = 0, fail = 0;
for (const [input, expect] of CASES) {
  const got = bahtText(input);
  if (got === expect) { pass++; console.log(`  ✓ ${input} → ${got}`); }
  else { fail++; console.log(`  ✗ ${input} → ได้ "${got}" ควรเป็น "${expect}"`); }
}
console.log(`\nสรุป: ผ่าน ${pass} / ล้มเหลว ${fail}`);
process.exit(fail ? 1 : 0);
